/*UAT_Filter Brand and SubBrands */
WITH CTE_TMP AS (
  SELECT *,
  year(max(DT_INI) over(partition by kpi_name)) yr_max
  FROM {{KPI_TABLE}}
  WHERE KPI_NAME IN ('volume', 'nr') AND VERSION_ID IN (62,61)
)
, CTE_FILTER AS (
  SELECT COUNTRY_ISO_CODE_3,
         RAW_BRAND AS BRAND_FAMILY,
         CASE WHEN LEVEL_3 = 'N/A' THEN 'All' ELSE LEVEL_3 END AS SUB_BRAND,
         SUM(CASE WHEN KPI_NAME = 'volume' AND YEAR(DT_INI) = yr_max THEN AC ELSE 0 END) AS AC_CY_VOLUME,
         SUM(CASE WHEN KPI_NAME = 'volume' AND YEAR(DT_INI) = yr_max-1 THEN AC ELSE 0 END) AS AC_LY_VOLUME,
         SUM(CASE WHEN KPI_NAME = 'nr' AND YEAR(DT_INI) = yr_max THEN AC ELSE 0 END) AS AC_CY_NR,
         SUM(CASE WHEN KPI_NAME = 'nr' AND YEAR(DT_INI) = yr_max-1 THEN AC ELSE 0 END) AS AC_LY_NR
  FROM CTE_TMP
  GROUP BY COUNTRY_ISO_CODE_3, RAW_BRAND, LEVEL_3
)
SELECT DISTINCT COUNTRY_ISO_CODE_3, BRAND_FAMILY, SUB_BRAND
FROM CTE_FILTER
WHERE (AC_CY_VOLUME > 0 AND AC_LY_VOLUME > 0) AND (AC_CY_NR > 0 AND AC_LY_NR > 0)
ORDER BY 1, 2, 3
